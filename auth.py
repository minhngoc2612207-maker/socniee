def hash_password(password: str) -> str:
    """Hashes password with bcrypt (12 rounds)."""
    pw_bytes = password.encode("utf-8")
    salt = bcrypt.gensalt(rounds=12)
    return bcrypt.hashpw(pw_bytes, salt).decode("utf-8")


def verify_password(password: str, hashed: str) -> bool:
    """Verifies password against stored hash with bcrypt and pbkdf2 fallback."""
    if not hashed:
        return False
    pw_bytes = password.encode("utf-8")
    try:
        if hashed.startswith("$2b$") or hashed.startswith("$2a$"):
            return bcrypt.checkpw(pw_bytes, hashed.encode("utf-8"))
        # Fallback for seed hashes generated by pbkdf2:sha256
        return check_password_hash(hashed, password)
    except Exception:
        return False


def generate_recovery_codes(count: int = 8) -> list:
    """
    Generates 8 single-use recovery codes in XXXX-XXXX format.
    Uses unambiguous characters (no 0/O, 1/I, L).
    """
    chars = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ"
    codes = []
    for _ in range(count):
        part1 = "".join(secrets.choice(chars) for _ in range(4))
        part2 = "".join(secrets.choice(chars) for _ in range(4))
        codes.append(f"{part1}-{part2}")
    return codes


def hash_recovery_code(code: str) -> str:
    """Hashes recovery code using SHA-256 for secure database storage."""
    clean_code = code.replace("-", "").strip().upper()
    return hashlib.sha256(clean_code.encode("utf-8")).hexdigest()


def verify_and_consume_recovery_code(user_id: str, code: str) -> bool:
    """Verifies and burns a one-time recovery code."""
    code_hash = hash_recovery_code(code)
    rec = query_db("""
        SELECT id FROM user_recovery_codes 
        WHERE user_id = ? AND code_hash = ? AND is_used = 0
    """, (user_id, code_hash), one=True)
    if not rec:
        return False
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    execute_db("""
        UPDATE user_recovery_codes 
        SET is_used = 1, used_at = ? 
        WHERE id = ?
    """, (now_str, rec["id"]))
    log_audit("USE_RECOVERY_CODE", "users", user_id, after_data={"code_id": rec["id"]})
    return True


