def login_required(f):
    """
    Decorator: Đã bỏ toàn bộ rào cản đăng nhập.
    Tự động cấp quyền Chủ sở hữu Lê Minh Ngọc và cho phép truy cập trực tiếp mọi tính năng.
    """
